"""Part about commits."""

# - **feat**: Используется для добавления новой функциональности в проект
# - **fix**: Используется для исправления ошибок или багов в коде
# - **docs**: Используется для обновления или создания документации проекта
# - **style**: Используется для изменений, которые не влияют на функциональность кода, но улучшают его читаемость или соответствие определенным стандартам
# - **refactor**: Используется для изменений, которые улучшают структуру или качество кода без добавления новой функциональности
# - **test**: Используется для добавления новых тестов или изменения существующих
# - **build**: Используется для изменений, связанных с процессом сборки проекта
# - **ci**: Используется для изменений, связанных с настройкой CI/CD
# - **perf**: Используется для изменений, направленных на улучшение производительности кода
# - **chore**: Используется для изменений, которые не подходят под другие категории

